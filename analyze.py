# LTspice values from the lab


def load_ltspice(path=LTSPICE_FILE):
    """Simulated values from the lab's LTspice DC sweeps, kept as text. '~' marks a rough reading."""
    table = {}
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            key = row.pop("circuit").strip()
            table[key] = {k.strip().lower(): v.strip() for k, v in row.items()}
    return table


def _num(text):
    return float(text.lstrip("~"))


def _places(text):
    return len(text.split(".")[1]) if "." in text else 0


def with_margins(sim):
    """Add NML = VIL - VOL and NMH = VOH - VIH to one row of LTspice values."""
    out = dict(sim)
    for name, a, b in (("nml", "vil", "vol"), ("nmh", "voh", "vih")):
        value = _num(sim[a]) - _num(sim[b])
        places = max(_places(sim[a]), _places(sim[b]))
        mark = "~" if sim[a].startswith("~") or sim[b].startswith("~") else ""
        out[name] = f"{mark}{value:.{places}f}"
    return out


# --------------------------------------------------------------------------
# Tables


def _fmt(value, places=2):
    return "n/a" if np.isnan(value) else f"{value:.{places}f}"


def _signed_mv(volts, mark=""):
    return f"{mark}{volts * 1000:+.0f}"


def results_markdown(results, sim) -> str:
    """The results block for the README (Markdown)."""
    lines = [
        "All values are in volts. Each measured value is the median over the full sweeps in its capture.",
        "",
        "| Circuit | Source | " + " | ".join(HEADERS) + " |",
        "|---|---|" + "---:|" * len(HEADERS),
    ]
    for r in results:
        cells = []
        for name in FIELDS:
            cells.append(_fmt(r.value(name), 3) + ("\\*" if r.wide(name) else ""))
        lines.append(f"| {r.label} | Measured | " + " | ".join(cells) + " |")
        if r.key in sim:
            s = with_margins(sim[r.key])
            lines.append(f"| {r.label} | LTspice | " + " | ".join(s[n] for n in FIELDS) + " |")
    wide = [r.widest_step(n) for r in results for n in ("vil", "vih") if r.wide(n)]
    if wide:
        lo, hi = min(wide), max(wide)
        span = f"{lo:.2f} V" if f"{lo:.2f}" == f"{hi:.2f}" else f"{lo:.2f} to {hi:.2f} V"
        lines += [
            "",
            f"\\* The slope here spans an input step of {span}, so this value is only as fine as that step.",
        ]
    lines += [
        "",
        "Switching point shift from the baseline:",
        "",
        "| Circuit | Measured VM (V) | Measured shift (mV) | LTspice VM (V) | LTspice shift (mV) |",
        "|---|---:|---:|---:|---:|",
    ]
    base = next((r for r in results if r.key == "baseline"), None)
    for r in results:
        shift = "" if base is None or r is base else _signed_mv(r.value("vm") - base.value("vm"))
        sim_vm = sim.get(r.key, {}).get("vm", "")
        sim_shift = ""
        if base is not None and r is not base and sim_vm and "vm" in sim.get(base.key, {}):
            base_vm = sim[base.key]["vm"]
            mark = "~" if sim_vm.startswith("~") or base_vm.startswith("~") else ""
            sim_shift = _signed_mv(_num(sim_vm) - _num(base_vm), mark)
        lines.append(f"| {r.label} | {_fmt(r.value('vm'), 3)} | {shift} | {sim_vm} | {sim_shift} |")
    lines += [
        "",
        "Capture checks:",
        "",
        "| File | Full sweeps | Steps per sweep | Input at the 0 V step (V) | VM spread over sweeps (mV) |",
        "|---|---:|---:|---:|---:|",
    ]
    for r in results:
        counts = sorted({len(c.vin) for c in r.curves})
        per_sweep = str(counts[0]) if len(counts) == 1 else f"{counts[0]}-{counts[-1]}"
        spread_mv = r.spread("vm") * 1000
        lines.append(f"| {r.capture.name} | {len(r.curves)} | {per_sweep} | {r.zero_step:.3f} | {spread_mv:.1f} |")
    return "\n".join(lines) + "\n"


def details_text(results) -> str:
    """Per-sweep numbers for the console."""
    out = []
    for r in results:
        c = r.capture
        out.append(
            f"{c.name}: {len(c.vin)} samples at {c.rate:g} S/s, {len(r.steps)} steps, "
            f"{len(r.curves)} full sweeps ({r.label})"
        )
        for i, cv in enumerate(r.curves, 1):
            out.append(
                f"  sweep {i}: {len(cv.vin)} steps  VOH {cv.voh:.3f}  VOL {cv.vol:.3f}  VM {cv.vm:.4f}  "
                f"VIL {cv.vil:.4f} (step {cv.vil_step:.3f})  VIH {cv.vih:.4f} (step {cv.vih_step:.3f})"
            )
    return "\n".join(out) + "\n"


def extract_block(text):
    """The generated block between the README markers, or None."""
    start = text.find(BLOCK_START)
    end = text.find(BLOCK_END)
    if start < 0 or end < start:
        return None
    return text[start + len(BLOCK_START) : end].strip("\n") + "\n"


def replace_block(text, block):
    start = text.find(BLOCK_START)
    end = text.find(BLOCK_END)
    if start < 0 or end < start:
        raise ValueError("README has no results markers")
    return text[: start + len(BLOCK_START)] + "\n" + block + text[end:]


