def expand(patterns):
    """Expand globs here too, since Windows shells pass them through unexpanded."""
    paths = []
    for p in patterns:
        hits = sorted(glob.glob(p)) if any(ch in p for ch in "*?[") else [p]
        paths.extend(hits)
    return [Path(p) for p in paths]


def main(argv=None):
    parser = argparse.ArgumentParser(description="Transfer-curve points from stepped ADALM2000 captures.")
    parser.add_argument("files", nargs="*", help="Scopy CSV exports (default: data/*.csv)")
    parser.add_argument("--out", default=str(ROOT / "results"), help="output folder (default: results/)")
    parser.add_argument("--readme", help="also refresh the results block in this README")
    parser.add_argument("--no-plots", action="store_true", help="skip the PNG plots")
    args = parser.parse_args(argv)

    paths = expand(args.files) if args.files else sorted((ROOT / "data").glob("*.csv"))
    if not paths:
        parser.error("no capture files found")
    results = analyze_files(paths)
    sim = load_ltspice()
    block = results_markdown(results, sim)

    sys.stdout.write(details_text(results) + "\n" + block)

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.md").write_text(block, encoding="utf-8", newline="\n")
    if not args.no_plots:
        plot_curves(results, out / "vtc_measured.png")
        plot_vs_ltspice(results, sim, out / "measured_vs_ltspice.png")

    if args.readme:
        readme = Path(args.readme)
        text = readme.read_text(encoding="utf-8")
        readme.write_text(replace_block(text, block), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
