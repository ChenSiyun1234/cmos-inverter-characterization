INK = "#0b0b0b"
INK_2 = "#52514e"
MUTED = "#898781"
GRID = "#e1e0d9"
AXIS = "#c3c2b7"
SURFACE = "#fcfcfb"
COLORS = {"baseline": "#2a78d6", "pmos": "#eb6834", "nmos": "#1baf7a"}


def _style(ax):
    ax.set_facecolor(SURFACE)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(AXIS)
    ax.tick_params(colors=INK_2, labelsize=9)
    ax.xaxis.label.set_color(INK_2)
    ax.yaxis.label.set_color(INK_2)
    ax.title.set_color(INK)


def _color(key, i):
    fallback = ["#2a78d6", "#eb6834", "#1baf7a"]
    return COLORS.get(key, fallback[i % len(fallback)])


def plot_curves(results, path):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig = plt.figure(figsize=(10, 8), facecolor=SURFACE)
    grid = fig.add_gridspec(2, 2, height_ratios=[1, 1.35], hspace=0.38, wspace=0.22)
    ax_t = fig.add_subplot(grid[0, :])
    ax_full = fig.add_subplot(grid[1, 0])
    ax_zoom = fig.add_subplot(grid[1, 1])

    # One sweep of the first capture, as the scope saw it.
    r0 = results[0]
    sweep = r0.sweeps[0]
    a, b = sweep[0].start, sweep[-1].stop
    t = r0.capture.time[a:b] - r0.capture.time[a]
    ax_t.plot(t, r0.capture.vin[a:b], color=MUTED, linewidth=1.5, label="Input (CH1)")
    ax_t.plot(t, r0.capture.vout[a:b], color=_color(r0.key, 0), linewidth=2, label="Output (CH2)")
    ax_t.set_xlabel("Time from the start of the sweep (s)")
    ax_t.set_ylabel("Voltage (V)")
    ax_t.set_title(f"{r0.label} capture, one sweep ({r0.capture.name})", fontsize=11, loc="left")
    ax_t.legend(frameon=False, fontsize=9, loc="center right")
    _style(ax_t)

    for ax, xlim in ((ax_full, (-0.1, 5.2)), (ax_zoom, (1.8, 3.3))):
        ax.plot([0, 5], [0, 5], color=AXIS, linewidth=1, zorder=1)
        for i, r in enumerate(results):
            x, y = r.median_curve()
            c = _color(r.key, i)
            vm = r.value("vm")
            ax.plot(
                x, y, color=c, linewidth=2, marker="o", markersize=4.5,
                markeredgecolor=SURFACE, markeredgewidth=0.8,
                label=f"{r.label} (VM {vm:.3f} V)", zorder=3,
            )
            ax.plot([vm], [vm], marker="o", markersize=9, markerfacecolor=SURFACE,
                    markeredgecolor=c, markeredgewidth=2, zorder=4)
        ax.set_xlim(*xlim)
        ax.set_ylim(-0.1, 5.3)
        ax.set_xlabel("Input (V)")
        _style(ax)
    ax_full.set_ylabel("Output (V)")
    ax_full.set_title("Measured transfer curves", fontsize=11, loc="left")
    ax_zoom.set_title("Near the switching point (rings: VM)", fontsize=11, loc="left")

    # Label the Vout = Vin line along its own angle.
    p0 = ax_full.transData.transform((3.6, 3.6))
    p1 = ax_full.transData.transform((4.6, 4.6))
    angle = float(np.degrees(np.arctan2(p1[1] - p0[1], p1[0] - p0[0])))
    ax_full.text(4.1, 4.1, "Vout = Vin", color=MUTED, fontsize=8, rotation=angle,
                 rotation_mode="anchor", ha="center", va="bottom")

    handles, labels = ax_full.get_legend_handles_labels()
    fig.legend(handles, labels, loc="lower center", ncol=len(labels), frameon=False,
               fontsize=9, bbox_to_anchor=(0.5, -0.01))
    fig.savefig(path, dpi=150, facecolor=SURFACE, bbox_inches="tight")
    plt.close(fig)


