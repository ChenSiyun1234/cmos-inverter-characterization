#!/usr/bin/env python3
"""Measure CMOS inverter transfer curves from stepped ADALM2000 captures.

Each capture is a Scopy oscilloscope export. CH1 is the inverter input and
CH2 is the output. The input is a staircase that repeats every few seconds,
so the script works on steps instead of raw samples:

1. Split CH1 into flat steps. Drop 5 ms at each end of a step and keep the
   median input and output of the rest.
2. Split the steps into sweeps from 0 V to 5 V. Keep the full sweeps.
3. On each sweep, find the transfer-curve points:
     VOH  output at the lowest input step
     VOL  output at the highest input step
     VM   input where the output equals the input
     VIL  going down from the steepest step, where the slope dVout/dVin
          comes back up to -1
     VIH  going up from the steepest step, where the slope comes back
          up to -1
   The slope at a step is the line through its two neighbors. (If steps
   are closer than 35 mV, it reaches out to the nearest steps past that.)
4. Report the median over the full sweeps.

Usage:
    python analyze.py data/*.csv
    python analyze.py data/*.csv --readme README.md
"""

from __future__ import annotations

import argparse
import csv
import glob
import sys
from dataclasses import dataclass
from itertools import pairwise
from pathlib import Path

import numpy as np
from numpy.lib.stride_tricks import sliding_window_view

ROOT = Path(__file__).resolve().parent
LTSPICE_FILE = ROOT / "sim" / "ltspice_values.csv"

UNITY = -1.0  # slope that defines VIL and VIH
WIDE_STEP = 0.1  # V; a slope that uses a wider input step gets a * in the table

# (part of the file name, key, label), in table order
CIRCUITS = [
    ("part2.4", "baseline", "Baseline"),
    ("strongerpmos", "pmos", "Two PMOS in parallel"),
    ("strongernmos", "nmos", "Two NMOS in parallel"),
]

FIELDS = ("voh", "vol", "vm", "vil", "vih", "nml", "nmh")
HEADERS = ("VOH", "VOL", "VM", "VIL", "VIH", "NML", "NMH")

BLOCK_START = "<!-- results:start (generated by analyze.py) -->"
BLOCK_END = "<!-- results:end -->"


# --------------------------------------------------------------------------
# Reading captures


@dataclass
class Capture:
    name: str
    meta: dict
    time: np.ndarray
    vin: np.ndarray
    vout: np.ndarray

    @property
    def rate(self) -> float:
        """Samples per second, from the header or from the time column."""
        try:
            return float(self.meta["Sample rate"])
        except (KeyError, ValueError):
            return 1.0 / float(np.median(np.diff(self.time)))


def load_capture(path, vin_column="CH1(V)", vout_column="CH2(V)") -> Capture:
    """Read a Scopy oscilloscope CSV export.

    Header lines start with ';'. Scopy writes the export date in the PC
    locale, so the file is read as bytes and header text is decoded loosely.
    """
    meta, rows, columns = {}, [], None
    with open(path, "rb") as f:
        for raw in f:
            line = raw.strip()
            if not line:
                continue
            if line.startswith(b";"):
                key, _, value = line[1:].decode("utf-8", "replace").partition(",")
                meta[key.strip()] = value.strip()
            elif columns is None:
                columns = line.decode("ascii").split(",")
            else:
                rows.append([float(v) for v in line.split(b",")])
    if columns is None or not rows:
        raise ValueError(f"{path}: no data rows")
    data = np.array(rows)
    col = {c: i for i, c in enumerate(columns)}
    return Capture(
        name=Path(path).name,
        meta=meta,
        time=data[:, col["Time(S)"]],
        vin=data[:, col[vin_column]],
        vout=data[:, col[vout_column]],
    )


# --------------------------------------------------------------------------
# Steps and sweeps


@dataclass
class Step:
    start: int  # first sample kept
    stop: int  # one past the last sample kept
    vin: float
    vout: float


def find_steps(vin, vout, rate, window=0.010, guard=0.005, min_len=0.020, jump=0.030):
    """Split a staircase input into flat steps.

    An edge is where the median of the next `window` seconds differs from the
    median of the previous `window` seconds by more than `jump` volts. The
    ADC code in these captures is about 20 mV, so 30 mV ignores one-code
    flicker but still catches a 50 mV step. Edges closer than `min_len`
    seconds count as one edge.
    """
    vin = np.asarray(vin, float)
    vout = np.asarray(vout, float)
    n = len(vin)
    w = max(2, round(window * rate))
    g = round(guard * rate)
    n_min = max(2, round(min_len * rate))
    if n < 2 * w + 1:
        return []

    med = np.median(sliding_window_view(vin, w), axis=1)  # med[k] = median(vin[k:k+w])
    change = np.zeros(n)
    change[w : n - w + 1] = np.abs(med[w:] - med[:-w])

    edges = []
    blocked = np.zeros(n, bool)
    for i in np.argsort(-change, kind="stable"):
        if change[i] <= jump:
            break
        if blocked[i]:
            continue
        # The change stays at its peak for a few samples around a clean edge.
        # Take the middle of that run so the guard trims both ends evenly.
        j = i
        while j + 1 < n and not blocked[j + 1] and change[j + 1] >= change[i] - 1e-9:
            j += 1
        edge = (i + j + 1) // 2
        edges.append(edge)
        blocked[max(0, edge - n_min + 1) : edge + n_min] = True

    bounds = [0, *sorted(edges), n]
    steps = []
    for a, b in pairwise(bounds):
        a, b = a + g, b - g
        if b - a >= n_min:
            steps.append(Step(a, b, float(np.median(vin[a:b])), float(np.median(vout[a:b]))))
    return steps


def split_sweeps(steps, drop=1.0):
    """Split steps into sweeps. A new sweep starts where the input falls by more than `drop` volts."""
    sweeps = []
    for step in steps:
        if not sweeps or step.vin < sweeps[-1][-1].vin - drop:
            sweeps.append([])
        sweeps[-1].append(step)
    return sweeps


def full_sweeps(steps, margin=0.1):
    """Keep the sweeps that reach both the lowest and the highest step level of the capture."""
    if not steps:
        return []
    lo = min(s.vin for s in steps)
    hi = max(s.vin for s in steps)
    return [
        sweep
        for sweep in split_sweeps(steps)
        if min(s.vin for s in sweep) <= lo + margin and max(s.vin for s in sweep) >= hi - margin
    ]


# --------------------------------------------------------------------------
# Transfer-curve points


def switching_point(vin, vout):
    """Input where the output equals the input, interpolated between two steps."""
    d = np.asarray(vout, float) - np.asarray(vin, float)
    idx = np.flatnonzero((d[:-1] > 0) & (d[1:] <= 0))
    if idx.size == 0:
        return float("nan")
    i = idx[0]
    return float(vin[i] + (vin[i + 1] - vin[i]) * d[i] / (d[i] - d[i + 1]))


def step_slopes(vin, vout, min_span=0.035):
    """Slope at each step, from the nearest steps at least `min_span` volts away on each side.

    With 50 mV steps these are just the two neighbors. The span keeps the
    slope from blowing up if the steps are finer than the ADC code.
    Returns (slope, lo, hi): lo and hi are the indices of the two steps used.
    Steps without a partner on both sides get NaN.
    """
    vin = np.asarray(vin, float)
    vout = np.asarray(vout, float)
    n = len(vin)
    s = np.full(n, np.nan)
    lo_idx = np.full(n, -1)
    hi_idx = np.full(n, -1)
    for i in range(n):
        lo = i - 1
        while lo >= 0 and vin[i] - vin[lo] < min_span:
            lo -= 1
        hi = i + 1
        while hi < n and vin[hi] - vin[i] < min_span:
            hi += 1
        if lo >= 0 and hi < n:
            s[i] = (vout[hi] - vout[lo]) / (vin[hi] - vin[lo])
            lo_idx[i], hi_idx[i] = lo, hi
    return s, lo_idx, hi_idx


def _cross(xa, xb, sa, sb):
    """Input between two steps where the slope equals UNITY (linear in the slope)."""
    ga, gb = sa - UNITY, sb - UNITY
    return float(xa + (xb - xa) * ga / (ga - gb))


def unity_gain_points(vin, vout):
    """VIL and VIH: where the slope crosses -1 on each side of the steepest step.

    Returns (vil, vih, vil_step, vih_step). Each *_step is the widest input
    step inside the two slopes around that crossing.
    """
    nan = float("nan")
    vin = np.asarray(vin, float)
    vout = np.asarray(vout, float)
    s, lo, hi = step_slopes(vin, vout)
    if np.all(np.isnan(s)):
        return nan, nan, nan, nan
    k = int(np.nanargmin(s))
    if s[k] >= UNITY:
        return nan, nan, nan, nan

    def widest(a, b):
        i0, i1 = min(lo[a], lo[b]), max(hi[a], hi[b])
        return float(np.max(np.diff(vin[i0 : i1 + 1])))

    vil = vih = vil_step = vih_step = nan
    for j in range(k - 1, -1, -1):  # walk down from the steepest step
        if np.isnan(s[j]):
            break
        if s[j] >= UNITY:
            vil = _cross(vin[j], vin[j + 1], s[j], s[j + 1])
            vil_step = widest(j, j + 1)
            break
    for j in range(k + 1, len(vin)):  # walk up from the steepest step
        if np.isnan(s[j]):
            break
        if s[j] >= UNITY:
            vih = _cross(vin[j - 1], vin[j], s[j - 1], s[j])
            vih_step = widest(j - 1, j)
            break
    return vil, vih, vil_step, vih_step


@dataclass
class Curve:
    """Transfer-curve points of one sweep."""

    vin: np.ndarray
    vout: np.ndarray
    voh: float
    vol: float
    vm: float
    vil: float
    vih: float
    vil_step: float
    vih_step: float

    @property
    def nml(self) -> float:
        return self.vil - self.vol

    @property
    def nmh(self) -> float:
        return self.voh - self.vih


def analyze_curve(vin, vout) -> Curve:
    """Find VOH, VOL, VM, VIL and VIH on one sweep of (input, output) step values."""
    order = np.argsort(np.asarray(vin, float), kind="stable")
    x = np.asarray(vin, float)[order]
    y = np.asarray(vout, float)[order]
    vil, vih, vil_step, vih_step = unity_gain_points(x, y)
    return Curve(x, y, float(y[0]), float(y[-1]), switching_point(x, y), vil, vih, vil_step, vih_step)


# --------------------------------------------------------------------------
# Whole captures


def identify(name):
    """(key, label) for a capture file name."""
    low = name.lower()
    for part, key, label in CIRCUITS:
        if part in low:
            return key, label
    return name, name


@dataclass
class Result:
    capture: Capture
    key: str
    label: str
    steps: list
    sweeps: list  # full sweeps, each a list of Step
    curves: list  # one Curve per full sweep

    def _values(self, name):
        return np.array([getattr(c, name) for c in self.curves], float)

    def value(self, name) -> float:
        """Median over the full sweeps."""
        v = self._values(name)
        return float(np.nanmedian(v)) if np.any(~np.isnan(v)) else float("nan")

    def spread(self, name) -> float:
        """Largest minus smallest value over the full sweeps."""
        v = self._values(name)
        return float(np.nanmax(v) - np.nanmin(v)) if np.any(~np.isnan(v)) else float("nan")

    def widest_step(self, name) -> float:
        """Widest input step behind the slope of VIL/VIH (and NML/NMH), over all sweeps."""
        attr = {"vil": "vil_step", "nml": "vil_step", "vih": "vih_step", "nmh": "vih_step"}.get(name)
        if attr is None:
            return 0.0
        return float(np.nanmax([getattr(c, attr) for c in self.curves]))

    def wide(self, name) -> bool:
        """True if the slope behind this value spans an input step wider than WIDE_STEP."""
        return self.widest_step(name) > WIDE_STEP

    @property
    def zero_step(self) -> float:
        """Input reading at the lowest step (the 0 V step)."""
        return float(np.median([c.vin[0] for c in self.curves]))

    def median_curve(self):
        """Per-step median over the full sweeps, for plots."""
        lengths = {len(c.vin) for c in self.curves}
        if len(lengths) != 1:
            return self.curves[0].vin, self.curves[0].vout
        return (
            np.median([c.vin for c in self.curves], axis=0),
            np.median([c.vout for c in self.curves], axis=0),
        )


def analyze_capture(capture: Capture) -> Result:
    key, label = identify(capture.name)
    steps = find_steps(capture.vin, capture.vout, capture.rate)
    sweeps = full_sweeps(steps)
    curves = [analyze_curve([s.vin for s in sw], [s.vout for s in sw]) for sw in sweeps]
    if not curves:
        raise ValueError(f"{capture.name}: no full sweep found")
    return Result(capture, key, label, steps, sweeps, curves)


def analyze_files(paths):
    results = [analyze_capture(load_capture(p)) for p in paths]
    order = {key: i for i, (_, key, _) in enumerate(CIRCUITS)}
    return sorted(results, key=lambda r: (order.get(r.key, len(order)), r.capture.name))


